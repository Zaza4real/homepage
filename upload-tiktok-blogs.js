async function uploadAllBlogPosts() {
  const token = localStorage.getItem('lypo_token_v1');
  
  if (!token) {
    console.error('❌ NOT LOGGED IN!');
    console.error('Please log in to dashboard.html first, then run this script again.');
    return;
  }
  
  console.log('🚀 Starting blog post upload...');
  console.log('📝 Total posts to upload:', BLOG_POSTS.length);
  console.log('');
  
  const results = [];
  
  for (let i = 0; i < BLOG_POSTS.length; i++) {
    const post = BLOG_POSTS[i];
    
    try {
      console.log(`📝 Uploading ${i + 1}/${BLOG_POSTS.length}: ${post.title}`);
      
      const response = await fetch('https://api.lypo.org/api/admin/blog/posts', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${token}`
        },
        body: JSON.stringify(post)
      });
      
      if (!response.ok) {
        const error = await response.json();
        console.error(`❌ Failed:`, error.error || error);
        results.push({ post: post.title, status: 'FAILED', error: error.error });
        continue;
      }
      
      const result = await response.json();
      console.log(`✅ SUCCESS! ID: ${result.post.id}, Slug: ${result.post.slug}`);
      console.log('');
      
      results.push({ post: post.title, status: 'SUCCESS', id: result.post.id, slug: result.post.slug });
      
    } catch (error) {
      console.error(`❌ Error:`, error.message);
      results.push({ post: post.title, status: 'ERROR', error: error.message });
    }
    
    // Small delay between uploads
    await new Promise(resolve => setTimeout(resolve, 1000));
  }
  
  console.log('');
  console.log('════════════════════════════════════════');
  console.log('🎉 UPLOAD COMPLETE!');
  console.log('════════════════════════════════════════');
  console.log('');
  console.log('📊 Results:');
  results.forEach((r, i) => {
    if (r.status === 'SUCCESS') {
      console.log(`✅ ${i + 1}. ${r.post}`);
      console.log(`   URL: https://lypo.org/post/${r.slug}`);
    } else {
      console.log(`❌ ${i + 1}. ${r.post} - ${r.error}`);
    }
  });
  
  const successCount = results.filter(r => r.status === 'SUCCESS').length;
  console.log('');
  console.log(`✅ Successfully uploaded: ${successCount}/${BLOG_POSTS.length} posts`);
  console.log('');
  console.log('🎯 Next steps:');
  console.log('1. Go to https://lypo.org/blog.html');
  console.log('2. Verify all posts are visible');
  console.log('3. Promote on social media!');
  console.log('');
  console.log('🚀 DONE!');
}

